#Sample Student Data Analysis
scores = [75, 82, 90, 68, 95]
total = sum(scores) 
average = total / len(scores) 
highest = max(scores) 
lowest = min(scores)

print("Student Score Analysis") 
print("----------------------") 
print("Scores:", scores) 
print("Total score:", total) 
print("Average score:", average) 
print("Highest score:", highest) 
